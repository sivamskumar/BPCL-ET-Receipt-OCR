-- ============================================================
-- Fuel Station Shift Reconciliation System
-- Database Migration V8
--
-- Purpose:
--   1. Create nozzle-wise fuel-sale calculation records.
--   2. Create employee cash-denomination entries.
--   3. Create consolidated employee coins entries.
--   4. Create consolidated TID-device collection entries.
--   5. Create customer credit-sale records.
--   6. Create expense and adjustment records.
--
-- Important business rules:
--
--   Fuel quantity:
--       Quantity Sold = End VTOT - Start VTOT
--
--   Fuel sales:
--       Calculated Sales Amount =
--           Quantity Sold x applicable Price Per Litre
--
--   Price Per Litre:
--       Resolved from fuel_price for the station/fuel/time
--       and snapshotted into fuel_sale.
--
--   ATOT:
--       Preserved in receipt data but NOT used in current
--       sales/reconciliation calculations.
--
--   Cash:
--       Total Notes Amount =
--           SUM(cash_denomination_entry.calculated_amount)
--
--       Cash Total =
--           Total Notes Amount + coins_entry.amount
--
--   TID:
--       One consolidated device total per employee per shift.
--       It represents UPI + debit-card + credit-card collections.
--
--   Total Collections:
--       Cash Total
--       + TID Device Total
--       + Credit Sale Total (when applicable)
--
--   Difference Amount:
--       Total Collections - Calculated Sales Amount
--
--   Reconciliation totals themselves will be created in a
--   later migration.
-- ============================================================


-- ============================================================
-- 1. Fuel Sale
--
-- One calculated sales record for one historical
-- shift-nozzle assignment.
--
-- The exact employee/nozzle/fuel-type context comes from
-- shift_nozzle_assignment.
--
-- price_per_litre is resolved from fuel_price and snapshotted
-- here so historical calculations remain reproducible even
-- after fuel-price master data changes.
-- ============================================================

CREATE TABLE reconciliation.fuel_sale (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    shift_id BIGINT NOT NULL,
    shift_nozzle_assignment_id BIGINT NOT NULL,

    employee_id BIGINT NOT NULL,
    nozzle_id BIGINT NOT NULL,
    fuel_type_id BIGINT NOT NULL,

    start_receipt_reading_id BIGINT NOT NULL,
    end_receipt_reading_id BIGINT NOT NULL,

    start_vtot NUMERIC(19, 3) NOT NULL,
    end_vtot NUMERIC(19, 3) NOT NULL,

    quantity_sold NUMERIC(19, 3) NOT NULL,

    fuel_price_id BIGINT NOT NULL,
    price_per_litre NUMERIC(12, 3) NOT NULL,

    calculated_sales_amount NUMERIC(19, 2) NOT NULL,

    calculated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    calculation_version INTEGER NOT NULL DEFAULT 1,

    CONSTRAINT fk_fuel_sale_shift
        FOREIGN KEY (shift_id)
        REFERENCES reconciliation.shift (id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_fuel_sale_shift_nozzle_assignment
        FOREIGN KEY (shift_nozzle_assignment_id)
        REFERENCES reconciliation.shift_nozzle_assignment (id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_fuel_sale_employee
        FOREIGN KEY (employee_id)
        REFERENCES reconciliation.employee (id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_fuel_sale_nozzle
        FOREIGN KEY (nozzle_id)
        REFERENCES reconciliation.nozzle (id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_fuel_sale_fuel_type
        FOREIGN KEY (fuel_type_id)
        REFERENCES reconciliation.fuel_type (id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_fuel_sale_start_reading
        FOREIGN KEY (start_receipt_reading_id)
        REFERENCES reconciliation.receipt_nozzle_reading (id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_fuel_sale_end_reading
        FOREIGN KEY (end_receipt_reading_id)
        REFERENCES reconciliation.receipt_nozzle_reading (id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_fuel_sale_fuel_price
        FOREIGN KEY (fuel_price_id)
        REFERENCES reconciliation.fuel_price (id)
        ON DELETE RESTRICT,

    CONSTRAINT uk_fuel_sale_assignment_version
        UNIQUE (
            shift_nozzle_assignment_id,
            calculation_version
        ),

    CONSTRAINT ck_fuel_sale_end_vtot
        CHECK (
            end_vtot >= start_vtot
        ),

    CONSTRAINT ck_fuel_sale_quantity_non_negative
        CHECK (
            quantity_sold >= 0
        ),

    CONSTRAINT ck_fuel_sale_price_positive
        CHECK (
            price_per_litre > 0
        ),

    CONSTRAINT ck_fuel_sale_amount_non_negative
        CHECK (
            calculated_sales_amount >= 0
        ),

    CONSTRAINT ck_fuel_sale_calculation_version
        CHECK (
            calculation_version > 0
        )
);


-- ============================================================
-- 2. Cash Denomination Entry
--
-- Stores note quantity for one denomination for one employee
-- within one shift.
--
-- calculated_amount must be calculated by the backend:
--
--     denomination_value_snapshot x quantity
--
-- The browser must not supply the authoritative calculated
-- amount.
-- ============================================================

CREATE TABLE reconciliation.cash_denomination_entry (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    shift_id BIGINT NOT NULL,
    employee_id BIGINT NOT NULL,

    cash_denomination_id BIGINT NOT NULL,

    denomination_value_snapshot NUMERIC(12, 2) NOT NULL,

    quantity INTEGER NOT NULL,

    calculated_amount NUMERIC(19, 2) NOT NULL,

    entered_by BIGINT NOT NULL,
    entered_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    updated_at TIMESTAMPTZ,
    updated_by BIGINT,

    version BIGINT NOT NULL DEFAULT 0,

    CONSTRAINT fk_cash_denomination_entry_shift
        FOREIGN KEY (shift_id)
        REFERENCES reconciliation.shift (id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_cash_denomination_entry_employee
        FOREIGN KEY (employee_id)
        REFERENCES reconciliation.employee (id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_cash_denomination_entry_denomination
        FOREIGN KEY (cash_denomination_id)
        REFERENCES reconciliation.cash_denomination (id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_cash_denomination_entry_entered_by
        FOREIGN KEY (entered_by)
        REFERENCES reconciliation.application_user (id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_cash_denomination_entry_updated_by
        FOREIGN KEY (updated_by)
        REFERENCES reconciliation.application_user (id)
        ON DELETE RESTRICT,

    CONSTRAINT uk_cash_denomination_entry
        UNIQUE (
            shift_id,
            employee_id,
            cash_denomination_id
        ),

    CONSTRAINT ck_cash_denomination_entry_snapshot_positive
        CHECK (
            denomination_value_snapshot > 0
        ),

    CONSTRAINT ck_cash_denomination_entry_quantity
        CHECK (
            quantity >= 0
        ),

    CONSTRAINT ck_cash_denomination_entry_amount
        CHECK (
            calculated_amount >= 0
        )
);


