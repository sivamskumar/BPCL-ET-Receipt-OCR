-- ============================================================
-- 4. TID Collection
--
-- Stores one consolidated TID-device collection total for one
-- employee within one shift.
--
-- The amount represents the combined total received through
-- that TID device:
--
--     UPI
--     + Debit Card
--     + Credit Card
--
-- Example:
--
--     TID: TID12345       12,500.00
--
-- One TID/device total is maintained per employee per shift.
-- ============================================================

CREATE TABLE reconciliation.tid_collection (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    shift_id BIGINT NOT NULL,
    employee_id BIGINT NOT NULL,

    terminal_identifier VARCHAR(100) NOT NULL,

    amount NUMERIC(19, 2) NOT NULL,

    entered_by BIGINT NOT NULL,
    entered_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    updated_at TIMESTAMPTZ,
    updated_by BIGINT,

    version BIGINT NOT NULL DEFAULT 0,

    CONSTRAINT fk_tid_collection_shift
        FOREIGN KEY (shift_id)
        REFERENCES reconciliation.shift (id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_tid_collection_employee
        FOREIGN KEY (employee_id)
        REFERENCES reconciliation.employee (id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_tid_collection_entered_by
        FOREIGN KEY (entered_by)
        REFERENCES reconciliation.application_user (id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_tid_collection_updated_by
        FOREIGN KEY (updated_by)
        REFERENCES reconciliation.application_user (id)
        ON DELETE RESTRICT,

    CONSTRAINT uk_tid_collection_shift_employee
        UNIQUE (
            shift_id,
            employee_id
        ),

    CONSTRAINT ck_tid_collection_terminal_not_blank
        CHECK (
            BTRIM(terminal_identifier) <> ''
        ),

    CONSTRAINT ck_tid_collection_amount_non_negative
        CHECK (
            amount >= 0
        )
);


-- ============================================================
-- 5. Credit Sale
--
-- Represents fuel supplied to a customer on account/credit
-- for later settlement.
--
-- IMPORTANT:
--   This is NOT a credit-card transaction.
--
-- Credit-card payments are already included in tid_collection.
-- ============================================================

CREATE TABLE reconciliation.credit_sale (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    shift_id BIGINT NOT NULL,
    employee_id BIGINT NOT NULL,

    customer_name VARCHAR(200) NOT NULL,
    customer_reference VARCHAR(150),

    vehicle_number VARCHAR(50),

    amount NUMERIC(19, 2) NOT NULL,

    remarks VARCHAR(1000),

    entered_by BIGINT NOT NULL,
    entered_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    settlement_status VARCHAR(30) NOT NULL
        DEFAULT 'OUTSTANDING',

    settled_at TIMESTAMPTZ,

    version BIGINT NOT NULL DEFAULT 0,

    CONSTRAINT fk_credit_sale_shift
        FOREIGN KEY (shift_id)
        REFERENCES reconciliation.shift (id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_credit_sale_employee
        FOREIGN KEY (employee_id)
        REFERENCES reconciliation.employee (id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_credit_sale_entered_by
        FOREIGN KEY (entered_by)
        REFERENCES reconciliation.application_user (id)
        ON DELETE RESTRICT,

    CONSTRAINT ck_credit_sale_customer_not_blank
        CHECK (
            BTRIM(customer_name) <> ''
        ),

    CONSTRAINT ck_credit_sale_amount_positive
        CHECK (
            amount > 0
        ),

    CONSTRAINT ck_credit_sale_settlement_status
        CHECK (
            settlement_status IN (
                'OUTSTANDING',
                'PARTIALLY_SETTLED',
                'SETTLED',
                'CANCELLED'
            )
        ),

    CONSTRAINT ck_credit_sale_settled_at
        CHECK (
            settlement_status <> 'SETTLED'
            OR settled_at IS NOT NULL
        )
);


-- ============================================================
-- 6. Adjustment
--
-- Stores expenses and other authorized adjustments.
--
-- Amount is always stored as a positive value.
--
-- Its effect on reconciliation is determined by direction.
--
-- Example:
--
--     EXPENSE
--     amount = 350.00
--     direction = DEDUCT_FROM_ACCOUNTED_AMOUNT
-- ============================================================

CREATE TABLE reconciliation.adjustment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    shift_id BIGINT NOT NULL,

    employee_id BIGINT,

    adjustment_type VARCHAR(40) NOT NULL,

    direction VARCHAR(40) NOT NULL,

    amount NUMERIC(19, 2) NOT NULL,

    description VARCHAR(1000) NOT NULL,

    reference_number VARCHAR(150),

    approval_status VARCHAR(30) NOT NULL
        DEFAULT 'PENDING',

    approved_by BIGINT,
    approved_at TIMESTAMPTZ,

    occurred_at TIMESTAMPTZ NOT NULL,

    created_by BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    version BIGINT NOT NULL DEFAULT 0,

    CONSTRAINT fk_adjustment_shift
        FOREIGN KEY (shift_id)
        REFERENCES reconciliation.shift (id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_adjustment_employee
        FOREIGN KEY (employee_id)
        REFERENCES reconciliation.employee (id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_adjustment_approved_by
        FOREIGN KEY (approved_by)
        REFERENCES reconciliation.application_user (id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_adjustment_created_by
        FOREIGN KEY (created_by)
        REFERENCES reconciliation.application_user (id)
        ON DELETE RESTRICT,

    CONSTRAINT ck_adjustment_type
        CHECK (
            adjustment_type IN (
                'EXPENSE',
                'CASH_DEPOSIT',
                'FUEL_TESTING',
                'CALIBRATION',
                'FUEL_RETURN',
                'OTHER'
            )
        ),

    CONSTRAINT ck_adjustment_direction
        CHECK (
            direction IN (
                'ADD_TO_ACCOUNTED_AMOUNT',
                'DEDUCT_FROM_ACCOUNTED_AMOUNT'
            )
        ),

    CONSTRAINT ck_adjustment_amount_positive
        CHECK (
            amount > 0
        ),

    CONSTRAINT ck_adjustment_description_not_blank
        CHECK (
            BTRIM(description) <> ''
        ),

    CONSTRAINT ck_adjustment_approval_status
        CHECK (
            approval_status IN (
                'PENDING',
                'APPROVED',
                'REJECTED'
            )
        ),

    CONSTRAINT ck_adjustment_approval
        CHECK (
            approval_status <> 'APPROVED'
            OR (
                approved_by IS NOT NULL
                AND approved_at IS NOT NULL
            )
        )
);


