-- ============================================================
-- 5. Reconciliation Submission
--
-- Append-only history of initial submission and every
-- resubmission.
--
-- Submission Number:
--
--     1 = INITIAL
--     2+ = RESUBMISSION
--
-- Application validation shall enforce the sequence.
-- ============================================================

CREATE TABLE reconciliation.reconciliation_submission (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    reconciliation_id BIGINT NOT NULL,

    submission_number INTEGER NOT NULL,

    submission_type VARCHAR(20) NOT NULL,

    submitted_by BIGINT NOT NULL,
    submitted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    remarks VARCHAR(1000),

    CONSTRAINT fk_reconciliation_submission_reconciliation
        FOREIGN KEY (reconciliation_id)
        REFERENCES reconciliation.reconciliation (id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_reconciliation_submission_submitted_by
        FOREIGN KEY (submitted_by)
        REFERENCES reconciliation.application_user (id)
        ON DELETE RESTRICT,

    CONSTRAINT uk_reconciliation_submission_number
        UNIQUE (
            reconciliation_id,
            submission_number
        ),

    CONSTRAINT ck_reconciliation_submission_number
        CHECK (
            submission_number > 0
        ),

    CONSTRAINT ck_reconciliation_submission_type
        CHECK (
            submission_type IN (
                'INITIAL',
                'RESUBMISSION'
            )
        ),

    CONSTRAINT ck_reconciliation_initial_submission
        CHECK (
            (
                submission_number = 1
                AND submission_type = 'INITIAL'
            )
            OR
            (
                submission_number > 1
                AND submission_type = 'RESUBMISSION'
            )
        )
);


-- ============================================================
-- 6. Approval Decision
--
-- Append-only Level-1 and Level-2 approval history.
--
-- Level-1:
--
--   MATCHED
--       APPROVED
--
--   SHORTAGE / EXCESS
--       RETURNED_TO_EMPLOYEE
--
--   Persistent shortage/excess after resubmission
--       APPROVED_WITH_REMARKS
--
-- Level-2:
--
--       APPROVED
--       APPROVED_WITH_REMARKS
--       REJECTED
--
-- A Level-2 REJECTED decision transitions the workflow back to
-- RETURNED_TO_EMPLOYEE so corrections and resubmission can occur.
-- ============================================================

CREATE TABLE reconciliation.approval_decision (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    reconciliation_id BIGINT NOT NULL,

    reconciliation_submission_id BIGINT NOT NULL,

    submission_number INTEGER NOT NULL,

    approval_level VARCHAR(20) NOT NULL,

    action VARCHAR(40) NOT NULL,

    acted_by BIGINT NOT NULL,
    acted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    remarks VARCHAR(1000),
    reason VARCHAR(1000),

    previous_workflow_status VARCHAR(50) NOT NULL,
    new_workflow_status VARCHAR(50) NOT NULL,

    CONSTRAINT fk_approval_decision_reconciliation
        FOREIGN KEY (reconciliation_id)
        REFERENCES reconciliation.reconciliation (id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_approval_decision_submission
        FOREIGN KEY (reconciliation_submission_id)
        REFERENCES reconciliation.reconciliation_submission (id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_approval_decision_acted_by
        FOREIGN KEY (acted_by)
        REFERENCES reconciliation.application_user (id)
        ON DELETE RESTRICT,

    CONSTRAINT ck_approval_decision_submission_number
        CHECK (
            submission_number > 0
        ),

    CONSTRAINT ck_approval_decision_level
        CHECK (
            approval_level IN (
                'LEVEL_1',
                'LEVEL_2'
            )
        ),

    CONSTRAINT ck_approval_decision_action
        CHECK (
            action IN (
                'SUBMITTED',
                'RETURNED_TO_EMPLOYEE',
                'RESUBMITTED',
                'APPROVED',
                'APPROVED_WITH_REMARKS',
                'REJECTED'
            )
        ),

    CONSTRAINT ck_approval_decision_return_reason
        CHECK (
            action NOT IN (
                'RETURNED_TO_EMPLOYEE',
                'REJECTED'
            )
            OR (
                reason IS NOT NULL
                AND BTRIM(reason) <> ''
            )
        ),

    CONSTRAINT ck_approval_decision_remarks
        CHECK (
            action <> 'APPROVED_WITH_REMARKS'
            OR (
                remarks IS NOT NULL
                AND BTRIM(remarks) <> ''
            )
        ),

    CONSTRAINT ck_approval_decision_previous_status_not_blank
        CHECK (
            BTRIM(previous_workflow_status) <> ''
        ),

    CONSTRAINT ck_approval_decision_new_status_not_blank
        CHECK (
            BTRIM(new_workflow_status) <> ''
        )
);


